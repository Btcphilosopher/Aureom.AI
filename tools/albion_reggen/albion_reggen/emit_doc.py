"""Documentation emitter: Markdown generated from the same validated model.

Files: MEMORY_MAP.md, REGISTERS.md, RESET_VALUES.md, HARDWARE_PORTS.md,
FIRMWARE_EXAMPLES.md.  Every number printed here comes from the model; the
tests parse these tables back and compare them with the RTL, C and Rust
outputs.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

from . import GENERATOR_NAME, SCHEMA_VERSION, __version__
from .examples import render_steps_c, render_steps_rust, render_steps_text
from .model import Field, HwPort, Peripheral, RegInst, RegMap, Register


def _hdr(m: RegMap, title: str) -> str:
    return (f"# {title}\n\n"
            f"> Generated by `{GENERATOR_NAME}` {__version__} (definition schema {SCHEMA_VERSION}) from register map "
            f"`{m.name}` v{m.version[0]}.{m.version[1]}. **Do not edit** - edit the register definition.\n>\n"
            f"> semantic hash `{m.semantic_hash}`  \n> definition hash `{m.definition_hash}`\n\n")


def _esc(s: str) -> str:
    return s.replace("|", "\\|")


def _h(v: int, w: int) -> str:
    return f"0x{v:0{w // 4}x}"


def _reset_cell(r: Register) -> str:
    """Reset of a whole register as shown in tables: a hex value, `live` if every field reads a hardware input
    (there is no reset value), `-` if every field is a stateless command."""
    if all(f.access == "ro" and f.hw == "input" for f in r.fields):
        return "live"
    if all(f.access == "w1p" or (f.access == "wo" and f.hw == "none") for f in r.fields):
        return "-"
    return f"`{_h(r.reset, r.width)}`"


def _access_text(f: Field) -> str:
    a, h = f.access, f.hw
    if a == "ro":
        return {"const": "RO (constant)", "input": "RO (live hardware input)", "update": "RO (hardware-updated)"}[h]
    if a == "rw":
        return "RW" + (" (hardware may also write)" if h == "update" else "")
    if a == "wo":
        return "WO" + (" (stored, drives hardware)" if h == "out" else " (value ignored)")
    return {"w1c": "W1C", "w1s": "W1S", "w1p": "W1P (pulse)"}[a]


def _semantics(f: Field) -> str:
    a, h, pr = f.access, f.hw, f.precedence
    if a == "ro" and h == "const":
        return "Reads a constant."
    if a == "ro" and h == "input":
        return "Reads the live hardware value at the cycle the read is accepted. Writes are ignored."
    if a == "ro" and h == "update":
        return "Hardware-updated status register: hardware writes it with `hw_we`; software writes are ignored."
    if a == "rw":
        s = "Software read/write; byte enables update only the enabled bytes."
        if h == "update":
            s += (" Hardware may also write it; if both write in the same cycle **hardware wins**." if pr == "hw"
                  else " Hardware may also write it; if both write in the same cycle **software wins**.")
        return s
    if a == "wo":
        return ("Write-only; the value written is held and drives hardware; reads return 0." if h == "out"
                else "Write-only; the written value is ignored (the write itself is the event); reads return 0.")
    if a == "w1c":
        s = "Write 1 to clear a bit; writing 0 has no effect."
        if h == "event":
            s += (" Hardware sets bits with a per-bit event; if set and clear coincide the bit **stays set** (hardware wins)."
                  if pr == "hw" else " Hardware sets bits with a per-bit event; if set and clear coincide the bit **is cleared** (software wins).")
        return s
    if a == "w1s":
        s = "Write 1 to set a bit; writing 0 has no effect."
        if h == "event":
            s += (" Hardware clears bits with a per-bit event; if set and clear coincide the bit **is cleared** (hardware wins)."
                  if pr == "hw" else " Hardware clears bits with a per-bit event; if set and clear coincide the bit **stays set** (software wins).")
        return s
    return "Write 1 to generate a one-cycle pulse on the hardware output; reads return 0; holds no state."


def _connect_map(p: Peripheral) -> Dict[Tuple[str, str, str], str]:
    out: Dict[Tuple[str, str, str], str] = {}
    for r in p.registers:
        for k, e in r.connect:
            out[(r.name, "", k)] = e
        for f in r.fields:
            for k, e in f.connect:
                out[(r.name, f.name, k)] = e
    for k, e in p.connect:
        out[("", "", k)] = e
    return out


def emit_memory_map(m: RegMap) -> str:
    L = [_hdr(m, f"Memory map - {m.name}")]
    L.append("Bus protocol: **Albion Link Protocol v1** (AlbionCore). Addresses are 64-bit device-side bus addresses; "
             "registers are 32 or 64 bits wide at naturally aligned offsets and live inside 16-byte ALP words "
             "(the byte-enable mask selects the register).\n")
    L.append("## Regions\n")
    L.append("| Region | Base | Size | Space | Attributes | Origin |")
    L.append("|---|---|---|---|---|---|")
    used = {p.region for p in m.peripherals}
    for r in m.regions:
        if r.name not in used:
            continue
        attrs = "".join(c if on else "-" for c, on in zip("rwxpsc", (r.read, r.write, r.exec, r.priv_only, r.secure_only, r.cacheable)))
        L.append(f"| `{r.name}` | `{_h(r.base, 64)}` | {_size(r.size)} | {r.asid} | `{attrs} {r.mem_type}` | "
                 + ("**proposed by this map** (not yet in the ALP catalogue)" if r.proposed else "ALP catalogue") + " |")
    L.append("\nAttribute key: r read, w write, x execute, p privileged-only, s secure-only, c cacheable.\n")
    L.append("## Peripherals\n")
    L.append("| Peripheral | Base | Size | Region | Access | RTL binding |")
    L.append("|---|---|---|---|---|---|")
    for p in m.peripherals:
        ab = m.periph_attr_byte(p)
        acc = ("privileged" if ab & 8 else "any privilege") + (", secure only" if ab & 16 else "")
        L.append(f"| `{p.name}` | `{_h(p.base, 64)}` | {_size(p.size)} | `{p.region}` | {acc} | {p.rtl_status} |")
    L.append("\n## Register address map\n")
    L.append("| Address | Peripheral | Register | Width | Reset | Access |")
    L.append("|---|---|---|---|---|---|")
    for p in m.peripherals:
        for r in p.registers:
            acc = "/".join(sorted({f.access.upper() for f in r.fields}))
            if r.count == 1:
                L.append(f"| `{_h(p.base + r.offset, 64)}` | `{p.name}` | `{r.name}` | {r.width} | {_reset_cell(r)} | {acc} |")
            else:
                last = p.base + r.offset + (r.count - 1) * r.stride
                L.append(f"| `{_h(p.base + r.offset, 64)}` .. `{_h(last, 64)}` | `{p.name}` | `{r.name}[0..{r.count - 1}]` "
                         f"(stride {r.stride}) | {r.width} | {_reset_cell(r)} | {acc} |")
    L.append("")
    return "\n".join(L)


def _size(n: int) -> str:
    for unit, div in (("GiB", 1 << 30), ("MiB", 1 << 20), ("KiB", 1 << 10)):
        if n >= div and n % div == 0:
            return f"{n // div} {unit}"
    return f"{n} B"


def emit_registers(m: RegMap) -> str:
    L = [_hdr(m, f"Register reference - {m.name}")]
    L.append("## How accesses behave\n")
    L.append("* **Transactions.** A request is accepted on the cycle `req_valid && req_ready`; that is the only moment "
             "side effects happen, so a stalled request or a response that is not taken never repeats an effect.")
    L.append("* **Byte enables.** A write updates only the enabled byte lanes; a read returns the enabled lanes and zero "
             "elsewhere. A 32-bit register occupies 4 lanes of its 16-byte word, a 64-bit register 8.")
    L.append("* **Reserved bits** read 0 and ignore writes.")
    L.append("* **Errors** (precedence order): ALP legality (`BAD_OPCODE`, `ALIGN_ERR`, `BAD_BE`, `BAD_ATTR`, `ACCESS_DENIED` for an "
             "invalid domain) > address outside every peripheral `DECODE_ERR` > region check (`ACCESS_DENIED` for permission, "
             "privilege or security, `BAD_ATTR` for a non-device memory type on a device region) > an enabled byte lane that "
             "belongs to no register `DECODE_ERR` > write to a register with no writable field or read of one with no readable "
             "field `ACCESS_DENIED` > a write refused by its hardware gate `TARGET_ERR`. An error response has zero data and "
             "**no register changes**, even on registers the same access also touched.")
    L.append("* **Hardware outputs are registered**: they change on the clock edge ending the accept cycle.\n")
    for p in m.peripherals:
        ab = m.periph_attr_byte(p)
        L.append(f"## `{p.name}` - {p.description}\n")
        L.append(f"Window `{_h(p.base, 64)}` + {_size(p.size)}, region `{p.region}`, "
                 + ("privileged access only" if ab & 8 else "no privilege required") + ("; secure only" if ab & 16 else "") + ".\n")
        L.append(f"RTL binding: **{p.rtl_status}**" + (f" - {p.rtl_summary}" if p.rtl_summary else "") + "\n")
        L.append("| Offset | Register | Width | Reset | Description |")
        L.append("|---|---|---|---|---|")
        for r in p.registers:
            nm = r.name if r.count == 1 else f"{r.name}[0..{r.count - 1}]"
            L.append(f"| `{r.offset:#05x}` | `{nm}` | {r.width} | {_reset_cell(r)} | {_esc(r.description)} |")
        L.append("")
        for r in p.registers:
            nm = r.name if r.count == 1 else f"{r.name}[0..{r.count - 1}]"
            L.append(f"### `{p.name}.{nm}`\n")
            L.append(f"Offset `{r.offset:#x}`, {r.width}-bit" + (f", array of {r.count} with stride {r.stride} bytes" if r.count > 1 else "")
                     + (f", reset {_reset_cell(r)}" if _reset_cell(r) not in ("live", "-") else (", no reset value (live hardware inputs)" if _reset_cell(r) == "live" else ", stateless command register")) + ".  " + _esc(r.description) + "\n")
            flags = []
            if r.write_gate:
                flags.append("**write gate**: a write while the hardware gate input is low is refused with `TARGET_ERR` and has no effect")
            if r.wr_strobe:
                flags.append("**write strobe**: a one-cycle hardware pulse follows every accepted write")
            if r.rd_strobe:
                flags.append("**read strobe**: a one-cycle hardware pulse follows every accepted read (read has a side effect)")
            if not r.rmw_safe:
                flags.append("no read-modify-write helpers are generated (read side effect or stored write-only field)")
            for fl in flags:
                L.append(f"* {fl}")
            if flags:
                L.append("")
            L.append("| Bits | Field | Access | Reset | Description |")
            L.append("|---|---|---|---|---|")
            rows: List[Tuple[int, str]] = []
            for f in r.fields:
                bits = f"[{f.msb}:{f.lsb}]" if f.width > 1 else f"[{f.lsb}]"
                rs = "live" if (f.access == "ro" and f.hw == "input") else ("-" if (f.access == "w1p" or (f.access == "wo" and f.hw == "none")) else f"`{_h(f.reset, max(4, (f.width + 3) // 4 * 4))}`")
                irq = f" Interrupt source, enabled by `{f.interrupt_enable[0]}.{f.interrupt_enable[1]}`." if f.interrupt_enable else ""
                rows.append((f.lsb, f"| {bits} | `{f.name}` | {_access_text(f)} | {rs} | {_esc((f.description + ' ' if f.description else '') + _semantics(f) + irq)} |"))
            # reserved ranges
            cov = r.field_mask
            pos = 0
            while pos < r.width:
                if (cov >> pos) & 1:
                    pos += 1
                    continue
                start = pos
                while pos < r.width and not (cov >> pos) & 1:
                    pos += 1
                hi, lo = pos - 1, start
                bits = f"[{hi}:{lo}]" if hi != lo else f"[{lo}]"
                rows.append((lo, f"| {bits} | *reserved* | - | `0` | Reads 0; writes ignored. |"))
            for _, row in sorted(rows, key=lambda t: -t[0]):
                L.append(row)
            L.append("")
    return "\n".join(L)


def emit_reset(m: RegMap) -> str:
    L = [_hdr(m, f"Reset values - {m.name}")]
    L.append("All state resets asynchronously on `rst_ni` (active low; release it synchronously, see ALP-RST-03). "
             "After reset the response channel is empty, every pulse and strobe output is 0 and every stored field holds the "
             "value below. Fields marked *live* have no stored value: they read the hardware input.\n")
    L.append("| Address | Register | Reset (whole register) | Field resets |")
    L.append("|---|---|---|---|")
    for i in m.instances:
        r = i.reg
        parts = []
        for f in r.fields:
            if f.access == "ro" and f.hw == "input":
                parts.append(f"`{f.name}`=live")
            elif f.access == "w1p" or (f.access == "wo" and f.hw == "none"):
                continue
            else:
                parts.append(f"`{f.name}`={_h(f.reset, max(4, (f.width + 3) // 4 * 4))}")
        nm = f"{i.periph.name}.{r.name}" + (f"[{i.elem}]" if r.count > 1 else "")
        L.append(f"| `{_h(i.addr, 64)}` | `{nm}` | {_reset_cell(r)} | {', '.join(parts) or '-'} |")
    L.append("")
    return "\n".join(L)


def emit_ports(m: RegMap) -> str:
    L = [_hdr(m, f"Hardware ports - {m.name}")]
    L.append("Ports of `sf_reg_bank` besides the ALP link (`clk_i`, `rst_ni`, `req_*`, `rsp_*`). Array registers use one packed "
             "vector, element *i* at bit `i*width`. The *connects to* column is the RTL signal the port is wired to in the "
             "implemented SilicaFlux block (checked by `albion_reggen bindcheck`); `glue` means integration logic is needed.\n")
    for p in m.peripherals:
        cm = _connect_map(p)
        L.append(f"## `{p.name}` ({p.rtl_status})\n")
        if p.rtl_modules:
            L.append("Implemented RTL:\n")
            L.append("| Module | Role | Source |")
            L.append("|---|---|---|")
            for md in p.rtl_modules:
                src = f"`{md.archive}` : `{md.path}`" if md.path else "-"
                role = "bank replaces its register slave" if md.role == "replace" else "bank attaches to its control ports"
                L.append(f"| `{md.module}` | {role} | {src}" + (f" (sha256 `{md.sha256[:16]}...`)" if md.sha256 else "") + " |")
            L.append("")
        L.append("| Port | Dir | Width | Meaning | Connects to |")
        L.append("|---|---|---|---|---|")
        for q in m.hw_ports:
            if q.periph != p.name:
                continue
            tgt = cm.get((q.reg, q.field, q.kind))
            L.append(f"| `{q.name}` | {q.direction} | {q.width} | {_esc(q.doc)} | " + (f"`{tgt}`" if tgt else "glue") + " |")
        L.append("")
    return "\n".join(L)


def emit_examples(m: RegMap) -> str:
    L = [_hdr(m, f"Firmware examples - {m.name}")]
    L.append("Each example is defined once, as data, in the register definition. The C and Rust below are generated from those "
             "steps, and the tests compile both (`sf_regs_examples.h`, `sf_regs_examples.rs`).\n")
    for p in m.peripherals:
        for k, ex in enumerate(p.examples):
            L.append(f"## {p.name}: {ex['title']}\n")
            if ex["description"]:
                L.append(ex["description"] + "\n")
            L.extend(render_steps_text(p, ex["steps"]))
            L.append("\n**C**\n")
            L.append("```c")
            L.append(f"int sf_example_{p.name}_{k}(void)")
            L.append("{")
            L.extend("    " + x for x in render_steps_c(m, p, ex["steps"]))
            L.append("    return 0;")
            L.append("}")
            L.append("```\n")
            L.append("**Rust**\n")
            L.append("```rust")
            L.append(f"pub fn example_{p.name}_{k}<B: RegBus>(bus: &B) -> Result<(), ExampleError> {{")
            L.extend("    " + x for x in render_steps_rust(m, p, ex["steps"]))
            L.append("    Ok(())")
            L.append("}")
            L.append("```\n")
    if not any(p.examples for p in m.peripherals):
        L.append("*This register map defines no examples.*\n")
    return "\n".join(L)


def emit_all(m: RegMap) -> Dict[str, str]:
    return {
        "MEMORY_MAP.md": emit_memory_map(m),
        "REGISTERS.md": emit_registers(m),
        "RESET_VALUES.md": emit_reset(m),
        "HARDWARE_PORTS.md": emit_ports(m),
        "FIRMWARE_EXAMPLES.md": emit_examples(m),
    }
