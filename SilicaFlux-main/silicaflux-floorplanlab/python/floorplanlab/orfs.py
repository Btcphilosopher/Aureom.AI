"""OpenROAD-flow-scripts integration.

FloorplanLab never re-implements ORFS: it writes a design ``config.mk`` (plus
the hook Tcl ORFS documents: SDC_FILE, IO_CONSTRAINTS, MACRO_PLACEMENT_TCL,
PDN_TCL, POST_PDN_TCL) and calls the ORFS Makefile targets of the pinned
revision (``synth``; ``do-2_1_floorplan`` ... ``do-3_place``).  Each call is
logged, timed and its exit status recorded; a non-zero status stops the run.

Synthesis is shared: its key hashes the RTL, defines, parameters, SDC, platform
libraries and tool versions, so every floorplan experiment that uses the same
key implements the *identical* netlist (fair comparisons, GATE 14).
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path

from .config import PROJECT, ConfigError, DesignConfig, PlatformProfile, RunSpec, tool_env

RESULTS = PROJECT / "results"

FLOORPLAN_STEPS = ["do-2_1_floorplan", "do-2_2_floorplan_io", "do-2_3_floorplan_tdms",
                   "do-2_4_floorplan_macro", "do-2_5_floorplan_tapcell"]
PDN_STEPS = ["do-2_6_floorplan_pdn", "do-2_floorplan"]
PLACE_STEPS = ["do-3_1_place_gp_skip_io", "do-3_2_place_iop", "do-3_3_place_gp",
               "do-3_4_place_resized", "do-3_5_place_dp", "do-3_place", "do-3_place.sdc"]


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tools() -> dict[str, str]:
    env = tool_env()
    return {k: env[k] for k in ("ORFS_FLOW", "OPENROAD_EXE", "YOSYS_EXE", "KLAYOUT_EXE", "IHP_SRAM") if k in env}


def tool_versions() -> dict[str, str]:
    t = tools()
    out: dict[str, str] = {}

    def run(cmd):
        try:
            return subprocess.run(cmd, capture_output=True, text=True, timeout=60).stdout.strip()
        except Exception as e:  # pragma: no cover - reported, not hidden
            return f"UNAVAILABLE ({e})"

    out["openroad"] = run([t.get("OPENROAD_EXE", "openroad"), "-version"]).splitlines()[0] if Path(t.get("OPENROAD_EXE", "")).exists() else "MISSING"
    out["yosys"] = run([t.get("YOSYS_EXE", "yosys"), "-V"]).split(" (")[0] if Path(t.get("YOSYS_EXE", "")).exists() else "MISSING"
    flow = Path(t.get("ORFS_FLOW", ""))
    if (flow.parent / ".git").exists():
        out["orfs"] = run(["git", "-C", str(flow.parent), "rev-parse", "HEAD"])
    else:
        out["orfs"] = "MISSING"
    out["klayout"] = run([t.get("KLAYOUT_EXE", "klayout"), "-zz", "-v"]) if Path(t.get("KLAYOUT_EXE", "")).exists() else "MISSING"
    out["python"] = run(["python3", "--version"])
    return out


def git_revision() -> str:
    try:
        rev = subprocess.run(["git", "-C", str(PROJECT), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(PROJECT), "status", "--porcelain", "--", "."],
                               capture_output=True, text=True).stdout.strip()
        return rev + ("+dirty" if dirty else "")
    except Exception:
        return "unknown"


@dataclass
class StepResult:
    target: str
    returncode: int
    seconds: float
    log: str


@dataclass
class OrfsContext:
    design: DesignConfig
    platform: PlatformProfile
    work_home: Path
    variant: str = "base"
    extra_env: dict[str, str] = field(default_factory=dict)

    @property
    def results_dir(self) -> Path:
        return self.work_home / "results" / self.platform.orfs_platform / self.design.name / self.variant

    @property
    def reports_dir(self) -> Path:
        return self.work_home / "reports" / self.platform.orfs_platform / self.design.name / self.variant

    @property
    def logs_dir(self) -> Path:
        return self.work_home / "logs" / self.platform.orfs_platform / self.design.name / self.variant

    @property
    def inputs_dir(self) -> Path:
        return self.work_home / "inputs"

    @property
    def config_mk(self) -> Path:
        return self.inputs_dir / "config.mk"

    # ------------------------------------------------------------------ inputs
    def write_defines(self) -> Path:
        p = self.inputs_dir / "flp_defines.svh"
        lines = ["// generated by FloorplanLab: preprocessor defines for synthesis",
                 "// (ORFS ab2aaf0f has no VERILOG_DEFINES; Yosys keeps defines across files)"]
        lines += [f"`define {d}" for d in self.design.rtl.defines]
        p.write_text("\n".join(lines) + "\n")
        return p

    def write_sdc(self, period_ns: float) -> Path:
        tmpl = (PROJECT / self.design.sdc_template).read_text()
        tck = next((c.get("period_ns") for c in self.design.clock.secondary if c.get("name") == "tck"), 100.0)
        sdc = tmpl.replace("{{CLK_PERIOD_NS}}", f"{period_ns:g}").replace("{{TCK_PERIOD_NS}}", f"{tck:g}")
        if "{{" in sdc:
            raise ConfigError(f"unsubstituted placeholder in {self.design.sdc_template}")
        p = self.inputs_dir / "constraint.sdc"
        p.write_text(sdc)
        return p

    def base_vars(self, period_ns: float) -> dict[str, str]:
        d, pf = self.design, self.platform
        files = [str(self.write_defines())] + [str(f) for f in d.resolved_files(pf)]
        macro_lefs = [m.lef for m in pf.macros.values()]
        macro_libs = list(pf.macro_liberty().values())
        macro_gds = [m.gds for m in pf.macros.values() if m.gds]
        v = {
            "DESIGN_NAME": d.top,
            "DESIGN_NICKNAME": d.name,
            "PLATFORM": pf.orfs_platform,
            "VERILOG_FILES": " ".join(files),
            "VERILOG_INCLUDE_DIRS": " ".join(str(PROJECT / i) for i in d.rtl.include_dirs),
            "SDC_FILE": str(self.write_sdc(period_ns)),
            "ADDITIONAL_LEFS": " ".join(macro_lefs),
            "ADDITIONAL_LIBS": " ".join(macro_libs),
            "ADDITIONAL_GDS": " ".join(macro_gds),
            # keep the big RTL blocks as hierarchy so instance names carry
            # u_cpu/, u_tile/u_ve/ ... (logical grouping; flattened in OpenROAD)
            "SYNTH_HIERARCHICAL": "1",
            "MAX_UNGROUP_SIZE": "1000",
            "TNS_END_PERCENT": "100",
        }
        if d.rtl.top_params:
            v["VERILOG_TOP_PARAMS"] = " ".join(f"{k} {val}" for k, val in d.rtl.top_params.items())
        return v

    def write_config(self, variables: dict[str, str]) -> Path:
        self.inputs_dir.mkdir(parents=True, exist_ok=True)
        lines = ["# generated by SilicaFlux FloorplanLab -- ORFS design config (do not edit)"]
        for k, val in variables.items():
            lines.append(f"export {k} = {val}")
        self.config_mk.write_text("\n".join(lines) + "\n")
        return self.config_mk

    def orfs_env(self, names: list[str]) -> dict[str, str]:
        """Resolved ORFS variables for this design config (`make print-VAR`)."""
        t = tools()
        cmd = ["make", "-s", "-C", t["ORFS_FLOW"], f"DESIGN_CONFIG={self.config_mk}", f"WORK_HOME={self.work_home}",
               f"FLOW_VARIANT={self.variant}", f"OPENROAD_EXE={t['OPENROAD_EXE']}", f"YOSYS_CMD={t['YOSYS_EXE']}"]
        cmd += [f"print-{n}" for n in names]
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        out = {}
        for line in r.stdout.splitlines():
            if " = " in line:
                k, v = line.split(" = ", 1)
                if k in names:
                    out[k] = v.strip()
        missing = [n for n in names if n not in out]
        if missing:
            raise ConfigError(f"ORFS did not resolve {missing}: {r.stderr[-500:]}")
        return out

    # ------------------------------------------------------------------ execution
    def make(self, targets: list[str], log_name: str, timeout: int = 6 * 3600) -> StepResult:
        t = tools()
        flow = Path(t["ORFS_FLOW"])
        log_dir = self.work_home / "flp_logs"
        log_dir.mkdir(parents=True, exist_ok=True)
        log = log_dir / f"{log_name}.log"
        for d in (self.results_dir, self.reports_dir, self.logs_dir, self.work_home / "objects" /
                  self.platform.orfs_platform / self.design.name / self.variant):
            d.mkdir(parents=True, exist_ok=True)   # ORFS do-* steps expect these (do-floorplan creates them)
        cmd = ["make", "-C", str(flow), f"DESIGN_CONFIG={self.config_mk}", f"WORK_HOME={self.work_home}",
               f"FLOW_VARIANT={self.variant}", f"OPENROAD_EXE={t['OPENROAD_EXE']}",
               f"YOSYS_CMD={t['YOSYS_EXE']}", f"KLAYOUT_CMD={t.get('KLAYOUT_EXE', 'klayout')}"] + targets
        env = dict(os.environ)
        env.update(self.extra_env)
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        t0 = time.time()
        with open(log, "w") as fh:
            fh.write("# " + " ".join(cmd) + "\n")
            fh.flush()
            try:
                rc = subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT, env=env, timeout=timeout).returncode
            except subprocess.TimeoutExpired:
                fh.write(f"\nFLOORPLANLAB: TIMEOUT after {timeout} s\n")
                rc = 124
        return StepResult(" ".join(targets), rc, round(time.time() - t0, 1), str(log))

    def openroad(self, script: Path, log_name: str, env_vars: dict[str, str], timeout: int = 4 * 3600,
                 gui: bool = False) -> StepResult:
        """Run a FloorplanLab analysis Tcl in OpenROAD with ORFS-like environment.
        gui=True: `openroad -gui` with an offscreen Qt platform (image rendering);
        the script must call exit itself."""
        t = tools()
        log_dir = self.work_home / "flp_logs"
        log_dir.mkdir(parents=True, exist_ok=True)
        log = log_dir / f"{log_name}.log"
        env = dict(os.environ)
        env.update(self.extra_env)
        env.update(env_vars)
        if gui:
            env["QT_QPA_PLATFORM"] = "offscreen"
            cmd = [t["OPENROAD_EXE"], "-no_init", "-gui", str(script)]
        else:
            cmd = [t["OPENROAD_EXE"], "-no_init", "-exit", str(script)]
        t0 = time.time()
        with open(log, "w") as fh:
            fh.write("# " + " ".join(cmd) + "\n")
            fh.flush()
            try:
                rc = subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT, env=env, timeout=timeout,
                                    cwd=str(self.work_home)).returncode
            except subprocess.TimeoutExpired:
                fh.write(f"\nFLOORPLANLAB: TIMEOUT after {timeout} s\n")
                rc = 124
        return StepResult(script.name, rc, round(time.time() - t0, 1), str(log))


# --------------------------------------------------------------------------- synthesis
def synth_key(design: DesignConfig, platform: PlatformProfile, period_ns: float) -> str:
    h = hashlib.sha256()
    for f in design.resolved_files(platform):
        h.update(f.name.encode())
        h.update(sha256_file(f).encode())
    h.update(json.dumps({"defines": design.rtl.defines, "params": design.rtl.top_params,
                         "top": design.top, "period": period_ns,
                         "sdc": sha256_file(PROJECT / design.sdc_template)}, sort_keys=True).encode())
    for lib in platform.liberty_files() + list(platform.macro_liberty().values()):
        h.update(sha256_file(Path(lib)).encode())
    v = tool_versions()
    h.update((v.get("yosys", "") + v.get("orfs", "")).encode())
    return h.hexdigest()[:12]


def synth_context(design: DesignConfig, platform: PlatformProfile, period_ns: float) -> OrfsContext:
    key = synth_key(design, platform, period_ns)
    return OrfsContext(design, platform, RESULTS / "synth" / f"{design.name}__{platform.name}__{key}")


def import_synthesis(ctx: OrfsContext, synth: OrfsContext) -> dict:
    """Copy the shared netlist into a run's RESULTS_DIR (unchanged)."""
    ctx.results_dir.mkdir(parents=True, exist_ok=True)
    out = {}
    for name in ("1_synth.v", "1_synth.sdc", "clock_period.txt"):
        src = synth.results_dir / name
        if not src.is_file():
            raise ConfigError(f"synthesis output missing: {src} (run floorplan-synth first)")
        shutil.copy2(src, ctx.results_dir / name)
        out[name] = sha256_file(src)
    return out
