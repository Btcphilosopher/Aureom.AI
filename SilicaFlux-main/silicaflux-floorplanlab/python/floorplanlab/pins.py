"""I/O pin constraints and manual macro placement Tcl (ORFS hook files).

Pins: logical core pins only (OpenROAD ioPlacer ``place_pins`` honouring
``set_io_pin_constraint`` edge regions).  This is NOT a pad ring: pad cells,
ESD, power pads, seal ring and bonding are physical integration dependencies.
"""
from __future__ import annotations

import re
from pathlib import Path

from .config import DesignConfig, PinSpec
from .geometry import Box, Placement


def top_ports(netlist: Path, top: str) -> list[str]:
    """Bit-blasted top-level port names from the mapped Verilog netlist."""
    text = netlist.read_text(errors="replace")
    m = re.search(rf"^module\s+\\?{re.escape(top)}\s*\((.*?)\);(.*?)^endmodule", text, re.S | re.M)
    if not m:
        raise ValueError(f"top module {top} not found in {netlist}")
    body = m.group(2)
    ports: list[str] = []
    for d in re.finditer(r"^\s*(input|output|inout)\s+(?:wire\s+)?(\[(\d+):(\d+)\]\s*)?([^;]+);", body, re.M):
        names = [n.strip().lstrip("\\") for n in d.group(5).split(",")]
        for n in names:
            if d.group(2):
                hi, lo = int(d.group(3)), int(d.group(4))
                for i in range(min(hi, lo), max(hi, lo) + 1):
                    ports.append(f"{n}[{i}]")
            else:
                ports.append(n)
    return ports


def pin_groups(design: DesignConfig, spec: PinSpec) -> list[tuple[str, str, list[str]]]:
    out = []
    for g in design.io_plan.groups:
        out.append((g.name, spec.edge_overrides.get(g.name, g.edge), list(g.pins)))
    return out


def pin_match(port: str, pat: str) -> bool:
    """'*' and '?' are wildcards; everything else (including '[' ']' of bus bits)
    is literal.  A pattern also matches the bus base name (gpio_i* -> gpio_i[3])."""
    rx = re.compile("^" + "".join(".*" if c == "*" else "." if c == "?" else re.escape(c) for c in pat) + "$")
    return bool(rx.match(port) or rx.match(port.split("[")[0]))


def expand(ports: list[str], pats: list[str]) -> list[str]:
    return [p for p in ports if any(pin_match(p, x) for x in pats)]


def io_constraints_tcl(design: DesignConfig, spec: PinSpec, ports: list[str], die: Box) -> str:
    lines = ["# generated by SilicaFlux FloorplanLab -- IO_CONSTRAINTS (logical core pins, no pad ring)"]
    if spec.mode == "auto":
        lines.append("# pins.mode = auto: no edge constraints; ioPlacer chooses locations")
        return "\n".join(lines) + "\n"
    for g, edge, pats in pin_groups(design, spec):
        names = expand(ports, pats)
        if not names:
            continue
        if g == "clock_reset":
            # clock source near the centre of its edge (+- 15 % of the edge)
            length = die.w if edge in ("top", "bottom") else die.h
            c = length / 2
            lo, hi = c - 0.15 * length, c + 0.15 * length
            region = f"{edge}:{lo:.2f}-{hi:.2f}"
        else:
            region = f"{edge}:*"
        lines.append(f"# group {g} -> {edge}")
        lines.append(f"set_io_pin_constraint -pin_names {{{' '.join(names)}}} -region {region}")
    return "\n".join(lines) + "\n"


def place_pins_args(spec: PinSpec) -> str:
    return f"-min_distance {spec.min_distance_tracks} -min_distance_in_tracks -corner_avoidance {spec.corner_avoidance_um:g}"


def macro_placement_tcl(placements: list[Placement], lib_tcl: Path) -> str:
    lines = ["# generated by SilicaFlux FloorplanLab -- MACRO_PLACEMENT_TCL (manual macro placement)",
             f"source {lib_tcl}",
             "set flp_macro_placements {"]
    for p in placements:
        lines.append(f"  {{{{{p.inst}}} {p.master} {p.x:.3f} {p.y:.3f} {p.orient}}}")
    lines.append("}")
    lines.append("flp_place_macros $flp_macro_placements")
    return "\n".join(lines) + "\n"
