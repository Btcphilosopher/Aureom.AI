def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def iter_members():
    for archive, prefix, sub, members in SOURCES:
        apath = REPO_SF / archive
        if not apath.is_file():
            raise SystemExit(f"ERROR: source archive not found: {apath}")
        with zipfile.ZipFile(apath) as zf:
            names = set(zf.namelist())
            for m in members:
                full = prefix + m
                if full not in names:
                    raise SystemExit(f"ERROR: {full} not present in {archive}")
                yield archive, full, sub, m, zf.read(full)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify vendored files against the archives")
    args = ap.parse_args()

    manifest = []
    bad = 0
    for archive, full, sub, rel, data in iter_members():
        dst = DEST / sub / rel
        digest = sha256(data)
        manifest.append({"archive": f"SilicaFlux-main/{archive}", "member": full,
                         "vendored_as": f"third_party/{sub}/{rel}", "sha256": digest})
        if args.check:
            if not dst.is_file() or sha256(dst.read_bytes()) != digest:
                print(f"MISMATCH {dst.relative_to(PROJECT)}")
                bad += 1
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(data)
    archives = {}
    for archive, _, _, _ in SOURCES:
        archives[f"SilicaFlux-main/{archive}"] = sha256((REPO_SF / archive).read_bytes())
    if args.check:
        print(f"checked {len(manifest)} vendored files: {'OK' if bad == 0 else f'{bad} MISMATCH'}")
        return 1 if bad else 0
    (DEST / "PROVENANCE.json").write_text(json.dumps({"archives": archives, "files": manifest}, indent=2) + "\n")
    with open(DEST / "SHA256SUMS", "w") as fh:
        for e in manifest:
            fh.write(f"{e['sha256']}  {e['vendored_as']}\n")
    print(f"vendored {len(manifest)} files from {len(archives)} archives into {DEST.relative_to(PROJECT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
